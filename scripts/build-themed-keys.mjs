// Builds src/themed-keys.js from the image manifest produced when importing the bishop's
// Covenant Key folders (DEC-018). Run: node scripts/build-themed-keys.mjs <manifest.json>
import { readFileSync, writeFileSync } from "node:fs";

const manifest = JSON.parse(readFileSync(process.argv[2], "utf8"));
// Poster badge geometry in % of the poster (top-left of the first badge, step between
// badges, badge size), and the nine badges in reading order. null = Key not supplied yet.
const GROUPS = [
  { id: "sports", name: "Sports", poster: "/group-posters/Sports - Group 1 CK.png", grid: [3.5, 13.5, 31, 24.5, 31, 23.5],
    slots: ["football", "basketball", "golf", ["Swimming"], ["Volleyball"], "tennis", "soccer", "baseball", "track-and-field"] },
  { id: "outdoors", name: "Outdoors", poster: "/group-posters/Outdoors - Group 1 CK.png", grid: [4, 14.5, 31, 25, 30, 23],
    slots: ["bird-watching", "mountain-biking", "kayaking", "river-rafting", "camping", "hiking", "fishing", "astronomy", ["Horseback Riding"]] },
  { id: "animal-habitats", name: "Animal Habitats", poster: "/group-posters/Animal Habitats Group 1 CK.png", grid: [3.5, 15, 31, 25, 29, 22.5],
    slots: ["forest-life", "jungle-life", "polar-life", "ice-age-life", "insect-life", "pet-life", "desert-life", "ocean-life", "jurassic-life"] },
  { id: "crafts", name: "Crafts", poster: "/group-posters/Crafts - Group 1 CK.png", grid: [5.6, 13.5, 30.4, 24.3, 28, 21],
    slots: ["pottery", "woodworking", "metal-work", "sewing", "quilting", "weaving", "leatherwork", "beading", "origami"] },
  { id: "performing-arts", name: "Performing Arts", poster: "/group-posters/Performing Arts Group 1 CK.png", grid: [7.4, 13.8, 29.6, 23.2, 26, 20],
    slots: [["Acting"], "singing", ["String Instruments"], "brass-instruments", ["Percussion Instruments"], ["Woodwind Instruments"], ["Piano"], ["Electric Instruments"], ["Dancing"]] },
  { id: "additional", name: "Additional Keys", poster: null, grid: null, slots: ["geocaching", "savanna-life", "reading"] }
];
const DESCRIBE = {
  sports: name => `Learn the rules, skills, and spirit of ${name.toLowerCase()}.`,
  outdoors: name => `Explore ${name.toLowerCase()} safely and enjoy God's creation.`,
  "animal-habitats": name => `Discover the animals and plants of ${name.toLowerCase()} and how to protect their habitat.`,
  crafts: name => `Learn the tools and techniques of ${name.toLowerCase()} and make something of your own.`,
  "performing-arts": name => `Develop your talent in ${name.toLowerCase()} and use it to uplift others.`,
  additional: name => ({ geocaching: "Use navigation skills to find hidden treasures outdoors.", "savanna-life": "Discover the animals and plants of the savanna and how to protect their habitat.", reading: "Discover the joy of reading across many kinds of books." })[name]
};
const byId = new Map(manifest.map(key => [key.id, key]));
const keys = manifest.map(key => {
  const cover = key.pages.find(page => page.cover) || null;
  const pages = key.pages.filter(page => page !== cover);
  const description = (DESCRIBE[key.group])(key.group === "additional" ? key.id : key.name);
  return {
    id: key.id, name: key.name, description, group: key.group, icon: { image: key.badge },
    cover: cover && { src: cover.file, title: `${key.name} cover` },
    lessons: pages.map((page, i) => ({
      id: `${key.id}-page-${i + 1}`, keyId: key.id, number: i + 1, title: page.title,
      description: `Page ${i + 1} of ${pages.length} in the ${key.name} Covenant Key.`, estimatedDuration: "At your own pace",
      sourcePage: page.file,
      tasks: page.requirements ? ["Complete the requirements on this page.", "Review them with a parent, guardian, or leader."] : ["Study this page.", "Discuss or practice what you learned with a parent, guardian, or leader."],
      sections: []
    }))
  };
});
const groups = GROUPS.map(group => ({
  id: group.id, name: group.name, poster: group.poster,
  grid: group.grid && { x0: group.grid[0], y0: group.grid[1], dx: group.grid[2], dy: group.grid[3], w: group.grid[4], h: group.grid[5] },
  slots: group.slots.map((slot, i) => ({ row: Math.floor(i / 3), col: i % 3, ...(Array.isArray(slot) ? { comingSoon: slot[0] } : { keyId: slot }) }))
}));
for (const group of groups) for (const slot of group.slots) if (slot.keyId && !byId.has(slot.keyId)) throw Error(`No Key ${slot.keyId}`);
for (const key of keys) if (!groups.some(group => group.slots.some(slot => slot.keyId === key.id))) throw Error(`Key ${key.id} has no group`);
writeFileSync("src/themed-keys.js", `// Generated by scripts/build-themed-keys.mjs from the bishop's Covenant Key folders (DEC-018).
// Edit the build script, not this file. Page images live in content/keys/<key>/.
export const themedGroups = ${JSON.stringify(groups)};
export const themedKeys = ${JSON.stringify(keys)};
`);
console.log(`${keys.length} Keys, ${keys.reduce((n, key) => n + key.lessons.length, 0)} lessons, ${groups.length} groups`);
